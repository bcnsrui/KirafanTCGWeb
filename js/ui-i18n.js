const TABLES = { ko: KO, en: EN, ja: JA };

export function t(key, params = {}) {
  const lang = getLang();
  const table = TABLES[lang] || KO;
  let s = table[key] ?? KO[key] ?? EN[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}


