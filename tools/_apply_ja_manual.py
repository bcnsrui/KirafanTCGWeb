def rebuild_ja_puzzles(ja_map: dict[str, str]) -> None:
    puzzles = json.loads((ROOT / "data/puzzles.json").read_text(encoding="utf-8"))
    out = []
    for p in puzzles:
        q = dict(p)
        q["category"] = PUZZLE_CAT[p["category"]]
        q["title"] = PUZZLE_TITLE[p["title"]]

        def repl(m: re.Match, _map=ja_map) -> str:
            body = norm(m.group(1))
            return f"Debug.ShowHint[[{_map.get(body, body)}]]"

        q["source"] = HINT_RE.sub(repl, norm(p["source"]))
        out.append(q)
    (ROOT / "data/ja/puzzles.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    en_map = {
        norm(k): v
        for k, v in json.loads((ROOT / "data/en/puzzle-hints.json").read_text(encoding="utf-8")).items()
    }
    en_to_ja = {en_map[k]: ja_map[k] for k in ja_map if k in en_map}
    (ROOT / "data/ja/_puzzle_hints_ja.json").write_text(
        json.dumps(en_to_ja, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def main() -> None:
    ja_path = ROOT / "data/ja/puzzle-hints.json"
    ja_map = {norm(k): v for k, v in json.loads(ja_path.read_text(encoding="utf-8")).items()}
    applied = 0
    missing = []
    for ko, ja in MANUAL.items():
        key = norm(ko)
        if key not in ja_map:
            missing.append(ko[:40])
            continue
        ja_map[key] = ja
        applied += 1

    # fix speakers on any remaining ★ lines that still use EN names
    for k, v in list(ja_map.items()):
        if not v.startswith("★"):
            continue
        line, _, rest = v.partition("\n")
        sp = line[1:].strip()
        if sp in SPEAKERS:
            ja_map[k] = f"★{SPEAKERS[sp]}\n{rest}" if rest else f"★{SPEAKERS[sp]}"

    ja_path.write_text(json.dumps(ja_map, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rebuild_ja_puzzles(ja_map)
    build_puzzles_en.main()

    left = [(k, v) for k, v in ja_map.items() if is_latin_heavy(v)]
    print(f"applied {applied} missing_keys {len(missing)} still_latin {len(left)}")
    for k, v in left[:10]:
        print("---")
        print(v[:160])


if __name__ == "__main__":
    main()
